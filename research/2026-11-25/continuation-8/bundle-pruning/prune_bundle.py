#!/usr/bin/env python3
"""Conservative source pruning from Lean's actual constant dependency graph.

Never writes the canonical source.  Declaration spans are compiler-provided;
namespace/section/open commands outside an attached `... in` wrapper stay intact.
Proof-source identifier dependencies are retained in addition to kernel-term
dependencies.  Generated constants are associated with their nearest ranged
declaration ancestor.  Recompile the generated candidate before using it.
"""
from pathlib import Path
import collections
import hashlib
import json
import re

BASE = Path(__file__).resolve().parent
SOURCE = BASE / 'unpruned-L_meta_8323.lean'
EXPECTED_SHA = '22ae16e3eaca0035fe210c92696e783bd83d16acc65d3ae429836cef83db2dee'
raw = SOURCE.read_bytes()
assert hashlib.sha256(raw).hexdigest() == EXPECTED_SHA, 'Source/range snapshot mismatch'
source = raw.decode('utf-8')
lines = source.splitlines(keepends=True)
data = json.loads((BASE / 'dependencies.json').read_text())
rows = {r['name']: r for r in data['constants']}

# The inspected bundle contains no local inductive/structure/mutual commands.
# Refuse those rather than silently applying ordinary-declaration assumptions.
assert not re.search(r'(?m)^(?:inductive|structure|class|mutual)\b', source)

groups = []
for name, row in rows.items():
    r = row['range']
    if r is None:
        continue
    assert r['startColumn'] == 0, (name, 'unexpected nested declaration range')
    first, last = r['startLine'] - 1, r['endLine']
    if r['endColumn'] == 0:
        last -= 1
    assert 0 <= first < last <= len(lines), (name, r)
    assert re.match(r'(?:@\[|(?:private |protected |noncomputable )?(?:def|abbrev|lemma|theorem|instance)\b)',
                    lines[first]), (name, 'non-declaration range', lines[first])
    # Scoped options/open commands are part of this declaration's command.
    while first > 0 and re.match(r'^(?:set_option\b.*\bin|open\b.*\bin)\s*$', lines[first-1].strip()):
        first -= 1
    groups.append({'first': first, 'last': last, 'names': [name]})

# Merge overlapping spans, if a command produced more than one ranged constant.
groups.sort(key=lambda g: (g['first'], g['last']))
merged = []
for g in groups:
    if merged and g['first'] < merged[-1]['last']:
        merged[-1]['last'] = max(merged[-1]['last'], g['last'])
        merged[-1]['names'] += g['names']
    else:
        merged.append(g)
groups = merged
group_for = {n: i for i, g in enumerate(groups) for n in g['names']}

def owner(name):
    candidates = [name]
    private = re.match(r'^_private\.PEqualNP\.Outside\.L_meta_8323\.\d+\.(.+)$', name)
    if private:
        candidates.append(private.group(1))
    for p in candidates:
        while p:
            if p in group_for:
                return group_for[p]
            p = p.rsplit('.', 1)[0] if '.' in p else ''
    return None

owned = collections.defaultdict(list)
for n in rows:
    o = owner(n)
    if o is not None:
        owned[o].append(n)

# Every explicit declaration can be named by a namespace suffix.  Ambiguous
# suffixes conservatively retain all candidates, rather than guessing elaboration.
suffixes = collections.defaultdict(set)
for n in group_for:
    pieces = n.split('.')
    for k in range(len(pieces)):
        suffixes['.'.join(pieces[k:])].add(n)
identifier = re.compile(r"[^\W\d][\w']*(?:\.[^\W\d][\w']*)*", re.UNICODE)

term_needed = {n for n, r in rows.items() if r['needed']}
missing_owner = sorted(n for n in term_needed if owner(n) is None)
assert not missing_owner, ('Required constants without source owner', missing_owner)
keep = {owner(n) for n in term_needed}
reasons = collections.defaultdict(set)
for n in term_needed:
    reasons[owner(n)].add('final-kernel-closure')

# Both global local-module instances are needed for reliable re-elaboration.
for i, g in enumerate(groups):
    if any(re.match(r'^instance\b', lines[j]) for j in range(g['first'], g['last'])):
        keep.add(i)
        reasons[i].add('instance-registration')

processed = set()
while keep - processed:
    i = min(keep - processed)
    processed.add(i)
    g = groups[i]
    # Retain dependencies of *all* constants generated by a retained command,
    # including those not on the final theorem's direct kernel path.
    for n in owned[i]:
        for d in rows[n]['dependencies']:
            o = owner(d)
            if o is not None:
                keep.add(o)
                reasons[o].add('retained-command-kernel-dependency')
    text = ''.join(lines[g['first']:g['last']])
    for token in identifier.findall(text):
        for n in suffixes.get(token, ()):
            o = group_for[n]
            keep.add(o)
            reasons[o].add('conservative-proof-source-reference')

deleted = [g for i, g in enumerate(groups) if i not in keep]
delete_lines = set()
for g in deleted:
    delete_lines.update(range(g['first'], g['last']))
for n in term_needed:
    g = groups[owner(n)]
    assert not any(j in delete_lines for j in range(g['first'], g['last'])), n
for i in keep:
    for n in owned[i]:
        for d in rows[n]['dependencies']:
            o = owner(d)
            assert o is not None and o in keep, (n, d, 'lost kernel dependency')

candidate = ''.join(line for j, line in enumerate(lines) if j not in delete_lines)
out = BASE / 'slim-L_meta_8323.lean'
out.write_text(candidate)
report = {
    'input_sha256': EXPECTED_SHA,
    'output_sha256': hashlib.sha256(candidate.encode()).hexdigest(),
    'input_bytes': len(raw), 'output_bytes': len(candidate.encode()),
    'input_lines': len(lines), 'output_lines': len(candidate.splitlines()),
    'module_constants': len(rows), 'final_kernel_closure_constants': len(term_needed),
    'declaration_commands': len(groups), 'kept_declaration_commands': len(keep),
    'removed_declaration_commands': len(deleted),
    'needed_constants_without_source_owner': missing_owner,
    'no_required_declaration_removed': True,
    'retained_commands_closed_under_all_local_kernel_dependencies': True,
    'proof_source_identifier_closure': 'conservative all matching namespace suffixes',
    'kept': [dict(g, reasons=sorted(reasons[i]), generated_constants=owned[i])
             for i, g in enumerate(groups) if i in keep],
    'deleted': deleted,
    'unowned_module_constants': [n for n in rows if owner(n) is None],
}
(BASE / 'pruning-report.json').write_text(json.dumps(report, indent=2, ensure_ascii=False) + '\n')
print(json.dumps({k: v for k, v in report.items() if k not in {'kept','deleted','unowned_module_constants'}},
                 indent=2))
